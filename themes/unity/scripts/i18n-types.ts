#!/usr/bin/env node
// Writes assets/unity/js/i18n-keys.ts from the js_ tables in i18n/en.toml.
// That file types the keys that t() and tn() in i18n.ts take and the
// placeholders that each key's string fills. Run `npm run i18n:types`
// after adding, renaming, or removing a js_ key or a placeholder, and
// commit the result. i18n.test.ts fails while the committed file differs
// from this script's output.
import { readFileSync, writeFileSync } from "node:fs";

export const EN_TOML = new URL("../i18n/en.toml", import.meta.url);
export const KEYS_TS = new URL("../assets/unity/js/i18n-keys.ts", import.meta.url);

// The placeholder syntax that fill() in i18n.ts replaces.
const PLACEHOLDER = /\{(\w+)\}/g;

const HEADER = `// Generated by \`npm run i18n:types\` from the js_ tables in i18n/en.toml.
// Do not edit it. Edit en.toml and run the command again.`;

/** Every table in en.toml as key -> forms. The file holds flat `[key]`
 *  tables of `one` and `other` strings, so a line parser reads it. */
export function readCatalog(text: string): Map<string, Record<string, string>> {
  const out = new Map<string, Record<string, string>>();
  let current: Record<string, string> = {};
  for (const line of text.split("\n")) {
    const table = /^\[([^\]]+)\]\s*$/.exec(line);
    if (table) {
      current = {};
      out.set(table[1]!, current);
      continue;
    }
    const form = /^(\w+)\s*=\s*"((?:[^"\\]|\\.)*)"\s*$/.exec(line);
    if (form) current[form[1]!] = JSON.parse(`"${form[2]!}"`) as string;
  }
  return out;
}

function union(names: Iterable<string>): string {
  const sorted = [...new Set(names)].sort();
  return sorted.length ? sorted.map((name) => JSON.stringify(name)).join(" | ") : "never";
}

function property(key: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key);
}

/** The source of i18n-keys.ts for a catalog. A table with a `one` form is
 *  a plural, as in _partials/unity/ui/i18n.html, and tn() fills its {n}. */
export function renderKeys(catalog: ReadonlyMap<string, Readonly<Record<string, string>>>): string {
  const messages: string[] = [];
  const plurals: string[] = [];
  for (const key of [...catalog.keys()].filter((k) => k.startsWith("js_")).sort()) {
    const forms = catalog.get(key)!;
    const names = Object.values(forms).flatMap((text) => [...text.matchAll(PLACEHOLDER)].map((m) => m[1]!));
    if ("one" in forms) plurals.push(`  ${property(key)}: ${union(names.filter((name) => name !== "n"))};`);
    else messages.push(`  ${property(key)}: ${union(names)};`);
  }
  return [
    HEADER,
    "",
    "/** Each plain js_ key, which t() reads, with the names of the",
    " *  placeholders that its string fills. */",
    "export interface Messages {",
    ...messages,
    "}",
    "",
    "/** Each plural js_ key, which tn() reads, with the names of the",
    " *  placeholders that its forms fill besides {n}. */",
    "export interface Plurals {",
    ...plurals,
    "}",
    "",
  ].join("\n");
}

if (import.meta.main) writeFileSync(KEYS_TS, renderKeys(readCatalog(readFileSync(EN_TOML, "utf8"))));
